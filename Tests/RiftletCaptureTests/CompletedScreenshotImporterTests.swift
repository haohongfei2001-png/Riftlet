        XCTAssertEqual(try Data(contentsOf: root.appendingPathComponent("media").appendingPathComponent(record.image.fileName)), bytes)
    }

    func testBuiltInMarkerNeverChangesOriginAndDerivativeKeepsOriginalBytes() async throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let captures = root.appendingPathComponent("captures")
        try FileManager.default.createDirectory(at: captures, withIntermediateDirectories: true)
        let source = InteractiveScreenshotOutput.originalURL(in: captures, captureID: UUID())
        let original = try generatedPNG()
        try original.write(to: source)
        // Only a disposable fixture marker; no real capture or upload evidence.
        try markSyntheticScreenshot(source)
        let file = try InteractiveScreenshotSystemCapture.readOriginal(at: source)
        XCTAssertTrue(file.hasSystemScreenshotMetadata)
        let database = root.appendingPathComponent("queue.sqlite")
        let store = try QueueStore(databaseURL: database)
        let importer = PrivateAssetImporter(privateRoot: root, store: store)
        let imported = try await importer.importBuiltInScreenshot(original: source, outputDirectory: captures)
        let repeated = try await importer.importBuiltInScreenshot(original: source, outputDirectory: captures)
        XCTAssertEqual(imported.image.origin, .applicationScreenshot)
        XCTAssertEqual(repeated.id, imported.id)
        let edited = try await importer.importBuiltInScreenshot(original: source, editedPNG: original,
                                                               outputDirectory: captures)
        XCTAssertEqual(edited.image.origin, .applicationScreenshot)
        XCTAssertEqual(try Data(contentsOf: source), original)
        XCTAssertEqual(try Data(contentsOf: root.appendingPathComponent("media").appendingPathComponent(imported.image.fileName)), original)
        XCTAssertEqual(try Data(contentsOf: root.appendingPathComponent("media").appendingPathComponent(edited.image.fileName)), original)
        let visible = try FileManager.default.contentsOfDirectory(at: captures,
            includingPropertiesForKeys: nil, options: [.skipsHiddenFiles])
        XCTAssertTrue(visible.isEmpty)
        let reopened = try QueueStore(databaseURL: database)
        let records = try await reopened.assets(includeUsed: true)
        XCTAssertEqual(records.count, 2)
        XCTAssertTrue(records.allSatisfy { $0.image.origin == .applicationScreenshot })
    }

    func testBuiltInImportRejectsExistingSystemRecordWithoutRetaggingIt() async throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let captures = root.appendingPathComponent("captures")
        try FileManager.default.createDirectory(at: captures, withIntermediateDirectories: true)
        let source = InteractiveScreenshotOutput.originalURL(in: captures, captureID: UUID())
        let bytes = try generatedPNG()
        try bytes.write(to: source); try markSyntheticScreenshot(source)
        let store = try QueueStore(databaseURL: root.appendingPathComponent("queue.sqlite"))
        let importer = PrivateAssetImporter(privateRoot: root, store: store)
        let historical = try await importer.importCompletedScreenshot(at: source, origin: .systemScreenshot)
        do {
            _ = try await importer.importBuiltInScreenshot(original: source, outputDirectory: captures)
            XCTFail("Historical system provenance was borrowed for built-in admission")
        } catch RiftletError.modeMismatch {}
        let records = try await store.assets(includeUsed: true)
        XCTAssertEqual(records.count, 1)
        XCTAssertEqual(records.first?.id, historical.id)
        XCTAssertEqual(records.first?.image.origin, .systemScreenshot)
        XCTAssertEqual(records.first?.image.sourceKey, historical.image.sourceKey)
        XCTAssertEqual(try Data(contentsOf: source), bytes)
    }

    private func generatedPNG() throws -> Data {
        let context = try XCTUnwrap(CGContext(data: nil, width: 20, height: 12, bitsPerComponent: 8,
            bytesPerRow: 0, space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(CGColor(red: 0.2, green: 0.6, blue: 0.7, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: 20, height: 12))
        let bytes = NSMutableData()
        let destination = try XCTUnwrap(CGImageDestinationCreateWithData(bytes, UTType.png.identifier as CFString, 1, nil))
        CGImageDestinationAddImage(destination, try XCTUnwrap(context.makeImage()), nil)
        XCTAssertTrue(CGImageDestinationFinalize(destination))
        return bytes as Data
    }

    private func markSyntheticScreenshot(_ url: URL) throws {
        let bytes = try PropertyListSerialization.data(fromPropertyList: true, format: .binary, options: 0)
        XCTAssertEqual(bytes.withUnsafeBytes { setxattr(url.path, CaptureSource.metadataName, $0.baseAddress, $0.count, 0, 0) }, 0)
    }
}

private final class CompletedImportClock: @unchecked Sendable {
    private let lock = NSLock()
    private var value = Date()
    func read() -> Date { lock.lock(); defer { lock.unlock() }; return value }
    func advance() { lock.lock(); value.addTimeInterval(1); lock.unlock() }
}
