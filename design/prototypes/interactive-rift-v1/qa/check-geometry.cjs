const assert = require('node:assert/strict');
const RiftEngine = require('../src/rift-engine.js');
const record=(id,width,height)=>({id,width,height,status:'pending'});
const close=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-8, `${actual} != ${expected}`);
const insets={top:25,bottom:76};
const a=record('landscape',1920,1080), b=record('portrait',1080,1920), c=record('panorama',2400,400);
const typical=RiftEngine.layout([a,b,c],1440,900,insets,0);
close(typical.rows[0].imageFrame.width,72);close(typical.rows[0].imageFrame.height,40.5);
close(typical.rows[0].imageClipFrame.width,54);close(typical.rows[0].frame.width,71.15);close(typical.rows[0].frame.height,44);
close(typical.rows[1].imageClipFrame.width,23.625);close(typical.rows[1].frame.width,44);close(typical.rows[1].frame.height,56);
close(typical.rows[2].imageClipFrame.height,12);close(typical.rows[2].frame.height,44);
close(typical.rows[0].frame.y+typical.rows[0].frame.height/2,205);
const twelve=RiftEngine.layout(Array.from({length:12},(_,i)=>record('p'+i,1080,1920)),1440,900,insets,0);
assert.equal(twelve.capacity,12);assert.equal(twelve.rows.length,12);close(twelve.rows[0].frame.y+28,124);
close(twelve.lineFrame.width,.7);close(twelve.lineFrame.x,1431.65);
const empty=RiftEngine.layout([],1440,900,insets,0);close(empty.lineFrame.height,24);
const overflow=RiftEngine.layout(Array.from({length:21},(_,i)=>record('p'+i,1080,1920)),1440,900,insets,21);
assert.equal(overflow.firstVisibleIndex,9);assert.equal(overflow.rows[0].ordinal,10);assert.equal(overflow.rows.at(-1).ordinal,21);
const used=RiftEngine.layout([{...a,status:'used'},b],1440,900,insets,0);assert.equal(used.totalCount,1);assert.equal(used.rows[0].assetID,'portrait');assert.equal(used.rows[0].ordinal,1);
console.log('PASS: source-derived geometry fixtures, capacity, clipping, empty trace, overflow, used filtering.');
