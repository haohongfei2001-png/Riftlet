#!/usr/bin/env node
// Read the original SVG unchanged. Rasterize its full square viewBox at every
// required size; no padding, cropping, recoloring, shadow or replacement artwork.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const cp = require('node:child_process');
const zlib = require('node:zlib');
const { Resvg } = require('@resvg/resvg-js');

const repo = path.resolve(__dirname, '../..');
const source = path.join(repo, 'website-assets/riftlet.svg');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const requireFact = (value, reason) => { if (!value) throw new Error(reason); };
// Read actual native-decoder output, including PNG scanline filters. The PNGs
// here are bounded RGBA8 files generated by resvg/iconutil, not arbitrary input.
function pngPixels(data) {
  requireFact(data.subarray(0, 8).equals(Buffer.from('89504e470d0a1a0a', 'hex')), 'Expected PNG');
  const width = data.readUInt32BE(16), height = data.readUInt32BE(20);
  requireFact(width <= 1024 && height <= 1024 && data.subarray(24, 29).equals(Buffer.from([8, 6, 0, 0, 0])), 'Expected bounded RGBA8 PNG');
  const idat = [];
  for (let offset = 8; offset < data.length;) {
    const length = data.readUInt32BE(offset);
    requireFact(offset + length + 12 <= data.length, 'Truncated PNG');
    if (data.toString('ascii', offset + 4, offset + 8) === 'IDAT') idat.push(data.subarray(offset + 8, offset + 8 + length));
    offset += length + 12;
  }
  const raw = zlib.inflateSync(Buffer.concat(idat), { maxOutputLength: 5 * 1024 * 1024 });
  const stride = width * 4, pixels = Buffer.alloc(stride * height);
  requireFact(raw.length === (stride + 1) * height, 'Unexpected PNG scanlines');
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)]; requireFact(filter <= 4, 'Unsupported PNG filter');
    for (let x = 0; x < stride; x++) {
      const at = y * stride + x, a = x >= 4 ? pixels[at - 4] : 0;
      const b = y ? pixels[at - stride] : 0, c = y && x >= 4 ? pixels[at - stride - 4] : 0;
      const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
      const predictor = filter === 1 ? a : filter === 2 ? b : filter === 3 ? Math.floor((a + b) / 2)
        : filter === 4 ? (pa <= pb && pa <= pc ? a : pb <= pc ? b : c) : 0;
      pixels[at] = (raw[y * (stride + 1) + x + 1] + predictor) & 255;
    }
  }
  return { width, height, pixels };
}
requireFact(process.argv.length === 3 && process.platform === 'darwin', 'Usage on macOS: node generate.cjs NEW_ABSOLUTE_OUTPUT');
const output = process.argv[2];
requireFact(path.isAbsolute(output) && !fs.existsSync(output), 'Use a new absolute output directory');
requireFact(fs.realpathSync(path.dirname(output)) === path.dirname(output), 'Output parent must be a real directory');
fs.mkdirSync(output, { mode: 0o700 });
const iconset = path.join(output, 'Riftlet.iconset');
fs.mkdirSync(iconset);
const original = fs.readFileSync(source);
const slots = [];
const chunks = [];
const types = { '16:1': 'ic04', '32:1': 'ic05', '128:1': 'ic07', '256:1': 'ic08', '512:1': 'ic09',
  '16:2': 'ic11', '32:2': 'ic12', '128:2': 'ic13', '256:2': 'ic14', '512:2': 'ic10' };
function argbRepresentation(premultipliedRGBA) {
  // Native small ICNS slots store premultiplied ARGB planes. Use resvg's
  // original premultiplied raster directly, not the PNG's unassociated RGB.
  // Valid literal-only PackBits runs avoid any lossy color/alpha conversion.
  const parts = [Buffer.from('ARGB')];
  for (const channel of [3, 0, 1, 2]) {
    const plane = Buffer.alloc(premultipliedRGBA.length / 4);
    for (let i = 0; i < plane.length; i++) plane[i] = premultipliedRGBA[i * 4 + channel];
    for (let i = 0; i < plane.length; i += 128) {
      const segment = plane.subarray(i, i + 128);
      parts.push(Buffer.from([segment.length - 1]), segment);
    }
  }
  return Buffer.concat(parts);
}
for (const logicalSize of [16, 32, 128, 256, 512]) {
  for (const scale of [1, 2]) {
    const pixels = logicalSize * scale;
    const renderer = new Resvg(original, {
      fitTo: { mode: 'width', value: pixels },
      font: { loadSystemFonts: false },
    });
    requireFact(renderer.width === 112 && renderer.height === 112, 'Original SVG viewBox/size changed; review before regenerating');
    const image = renderer.render();
    requireFact(image.width === pixels && image.height === pixels, 'Raster dimensions differ');
    const filename = `icon_${logicalSize}x${logicalSize}${scale === 2 ? '@2x' : ''}.png`;
    const data = image.asPng();
    fs.writeFileSync(path.join(iconset, filename), data, { flag: 'wx' });
    const type = types[`${logicalSize}:${scale}`], header = Buffer.alloc(8);
    const representation = ['ic04', 'ic05'].includes(type) ? argbRepresentation(image.pixels) : data;
    header.write(type, 0, 'ascii'); header.writeUInt32BE(representation.length + 8, 4);
    chunks.push(header, representation);
    slots.push({ filename, logicalSize, scale, pixels, icnsType: type, sha256: sha(data) });
  }
}
const icon = path.join(output, 'Riftlet.icns');
// Preserve the renderer pixels in each native representation. iconutil's
// encoder on this OS copies unassociated small PNG values into ARGB planes;
// providing the original premultiplied planes avoids double-unpremultiplication.
const body = Buffer.concat(chunks), header = Buffer.alloc(8);
header.write('icns', 0, 'ascii'); header.writeUInt32BE(body.length + 8, 4);
fs.writeFileSync(icon, Buffer.concat([header, body]), { flag: 'wx' });
const decoded = path.join(output, 'decoded.iconset');
const result = cp.spawnSync('/usr/bin/iconutil', ['--convert', 'iconset', '--output', decoded, icon], { encoding: 'utf8' });
fs.writeFileSync(path.join(output, 'iconutil.stdout.log'), result.stdout || '', { flag: 'wx' });
fs.writeFileSync(path.join(output, 'iconutil.stderr.log'), result.stderr || '', { flag: 'wx' });
requireFact(result.status === 0 && fs.existsSync(icon), 'iconutil failed; retain output evidence');
requireFact(fs.readdirSync(decoded).filter(name => name.endsWith('.png')).length === slots.length, 'Native decoder did not recover every slot');
for (const slot of slots) {
  const expected = pngPixels(fs.readFileSync(path.join(iconset, slot.filename)));
  const actual = pngPixels(fs.readFileSync(path.join(decoded, slot.filename)));
  requireFact(expected.width === actual.width && expected.height === actual.height && expected.pixels.equals(actual.pixels),
    `Native decoded pixels differ: ${slot.filename}`);
}
requireFact(fs.readFileSync(source).equals(original), 'Source SVG changed during generation');
const manifest = {
  schema: 1,
  source: 'website-assets/riftlet.svg', sourceSHA256: sha(original),
  transformation: 'Unmodified full SVG rasterized at each required size; no crop, padding, color or shape edits',
  renderer: { package: '@resvg/resvg-js', version: require('@resvg/resvg-js/package.json').version,
    lockSHA256: sha(fs.readFileSync(path.join(__dirname, 'package-lock.json'))),
    generatorSHA256: sha(fs.readFileSync(__filename)) },
  container: { encoding: 'ICNS: original premultiplied ARGB planes for ic04/ic05; original PNG bytes for eight larger/Retina slots', nativeValidation: '/usr/bin/iconutil', toolSHA256: sha(fs.readFileSync('/usr/bin/iconutil')),
    platform: process.platform, architecture: process.arch, node: process.version },
  slots, icon: { filename: 'Riftlet.icns', sha256: sha(fs.readFileSync(icon)), bytes: fs.statSync(icon).size },
  nativeDecodedSlots: slots.length, allNativeDecodedRGBABytesEqual: true,
  runtimeDependencyAdded: false,
};
fs.writeFileSync(path.join(output, 'icon-generation.json'), JSON.stringify(manifest, null, 2) + '\n', { flag: 'wx' });
console.log(JSON.stringify({ result: 'ICON_GENERATED', sourceSHA256: manifest.sourceSHA256, iconSHA256: manifest.icon.sha256, slots: slots.length }));
